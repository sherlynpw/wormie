// SvelteKit's vite plugin overwrites response headers, so server.headers in
// dev/preview is ignored for routed responses. This plugin force-injects
// COOP/COEP/CORP on every response, which is required for sqlite-wasm's
// OPFS-SAH-Pool VFS (depends on SharedArrayBuffer / cross-origin isolation).
function crossOriginIsolation(): Plugin {
  const apply = (
    _req: unknown,
    res: { setHeader: (k: string, v: string) => void },
    next: () => void,
  ) => {
    res.setHeader('Cross-Origin-Opener-Policy', 'same-origin');
    res.setHeader('Cross-Origin-Embedder-Policy', 'require-corp');
    res.setHeader('Cross-Origin-Resource-Policy', 'same-origin');
    next();
  };
  return {
    name: 'cross-origin-isolation',
    configureServer(server) {
      server.middlewares.use(apply);
    },
    configurePreviewServer(server) {
      server.middlewares.use(apply);
    },
  };
}

// Serve scripts/wasm-cran/ at /wasm-cran/ in dev + preview. These files are
// regenerated by the build-wasm CI workflow and uploaded to R2; in production
// the Cloudflare Worker proxies the same path from R2. Keeping the URL
// identical across envs means client code never has to branch on NODE_ENV.
function wasmCranStatic(): Plugin {
  const SRC = path.resolve(import.meta.dirname, 'scripts/wasm-cran');
  const PREFIX = '/wasm-cran/';
  const contentTypeFor = (file: string) => {
    if (file.endsWith('.js') || file.endsWith('.mjs')) return 'application/javascript';
    if (file.endsWith('.wasm')) return 'application/wasm';
    if (file.endsWith('.data')) return 'application/octet-stream';
    if (file.endsWith('.metadata') || file.endsWith('.json')) return 'application/json';
    if (file.endsWith('.tgz') || file.endsWith('.gz')) return 'application/gzip';
    return 'application/octet-stream';
  };
  const apply = (
    req: { url?: string },
    res: {
      statusCode: number;
      setHeader: (k: string, v: string) => void;
      end: (b?: unknown) => void;
    },
    next: () => void,
  ) => {
    const url = req.url || '';
    if (!url.startsWith(PREFIX)) return next();
    const rel = url.slice(PREFIX.length).split('?')[0];
    if (rel.includes('..')) {
      res.statusCode = 400;
      res.end('Bad request');
      return;
    }
    const full = path.join(SRC, rel);
    if (!fs.existsSync(full) || !fs.statSync(full).isFile()) return next();
    res.setHeader('Content-Type', contentTypeFor(full));
    res.setHeader('Cache-Control', 'no-cache');
    res.setHeader('Cross-Origin-Resource-Policy', 'same-origin');
    res.end(fs.readFileSync(full));
  };
  return {
    name: 'wasm-cran-static',
    configureServer(server) {
      server.middlewares.use(apply);
    },
    configurePreviewServer(server) {
      server.middlewares.use(apply);
    },
  };
}

// KEGG can be excluded at build (license: do not redistribute the dump). Set
// DISABLE_KEGG=1 to drop KEGG data from the bundled DB and hide pathway UI.
// Injected as __KEGG_ENABLED__ and read via src/lib/config.ts.
const KEGG_ENABLED = !/^(1|true|yes|on)$/i.test((process.env.DISABLE_KEGG ?? '').trim());

