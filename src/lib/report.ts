// Markdown report builders for gene-detail and GSEA panels.
// Output is a self-contained .md with a data-freshness footer and citation list.

import type { GseaResult } from './db/client';
import type {
  GeneRow,
  GoAnnotation,
  PhenotypeRow,
  AnatomyRow,
  Ortholog,
  WormcatAssignment,
  NeuronalAssignment,
  CengenExpressionRow,
  CengenCoexprNeighbor,
  DiseaseAssociation,
} from './queries';

type VersionInfo = {
  version?: string;
  built_at?: string;
  sources?: Record<string, unknown>;
};

async function fetchVersion(): Promise<VersionInfo | null> {
  try {
    const r = await fetch('/data/version.json', { cache: 'no-store' });
    return r.ok ? ((await r.json()) as VersionInfo) : null;
  } catch {
    return null;
  }
}

function fence(s: string | null | undefined): string {
  return (s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

function citationFooter(v: VersionInfo | null): string {
  const lines: string[] = ['', '---', '', '## Data sources'];
  if (!v) {
    lines.push('_(version metadata unavailable)_');
    return lines.join('\n');
  }
  lines.push(`- WormBase release: ${(v.sources as any)?.wormbase?.release ?? '?'}`);
  lines.push(`- Gene Ontology: ${(v.sources as any)?.go?.date ?? '?'}`);
  lines.push(`- BioGRID: ${(v.sources as any)?.biogrid?.version ?? '?'}`);
  lines.push(`- Alliance expression: ${(v.sources as any)?.alliance_expression?.version ?? '?'}`);
  const cengen = (v.sources as any)?.cengen;
  if (cengen?.release) {
    lines.push(`- CeNGEN: ${cengen.release}${cengen.citation ? ' (' + cengen.citation + ')' : ''}`);
  }
  lines.push(`- Build: ${v.version ?? '?'} (built ${v.built_at ?? '?'})`);
  lines.push(`- Generated by wormie.rs.ht on ${new Date().toISOString()}`);
  return lines.join('\n');
}

export interface GeneReportInput {
  gene: GeneRow;
  go: GoAnnotation[];
  phenotypes: PhenotypeRow[];
  anatomy: AnatomyRow[];
  orthologs: Ortholog[];
  wormcat: WormcatAssignment | null;
  neuronal: NeuronalAssignment[];
  cengen: CengenExpressionRow[];
  cengenCoexpr: CengenCoexprNeighbor[];
  diseases: DiseaseAssociation[];
}

export async function buildGeneReport(input: GeneReportInput): Promise<string> {
  const v = await fetchVersion();
  const g = input.gene;
  const out: string[] = [];
  out.push(`# ${g.gene_name ?? g.wormbase_gene}`);
  out.push('');
  out.push(
    `**WBGene:** [${g.wormbase_gene}](https://www.wormbase.org/species/c_elegans/gene/${g.wormbase_gene})`,
  );
  if (g.sequence_name) out.push(`**Sequence:** \`${g.sequence_name}\``);
  if (g.entrez_id)
    out.push(`**Entrez:** [${g.entrez_id}](https://www.ncbi.nlm.nih.gov/gene/${g.entrez_id})`);
  if (g.gene_type) out.push(`**Type:** ${g.gene_type}`);
  if (g.status) out.push(`**Status:** ${g.status}`);
  out.push('');
  if (g.gene_class_description) {
    out.push(`> ${g.gene_class_description}`);
    out.push('');
  }
  if (g.concise_description) {
    out.push('## Concise description');
    out.push(g.concise_description);
    out.push('');
  }

  if (input.wormcat?.category_1) {
    const wc = input.wormcat;
    out.push('## WormCat');
    out.push(
      `${wc.category_1}${wc.category_2 ? ' › ' + wc.category_2 : ''}${wc.category_3 ? ' › ' + wc.category_3 : ''}`,
    );
    out.push('');
  }

  if (input.diseases.length > 0) {
    out.push('## Human diseases');
    out.push('| DOID | Name | Evidence count |');
    out.push('|---|---|---|');
    for (const d of input.diseases.slice(0, 20)) {
      out.push(`| \`${d.do_id}\` | ${fence(d.do_name)} | ${d.evidence_count} |`);
    }
    out.push('');
  }

  if (input.orthologs.length > 0) {
    out.push('## Orthologs (best calls)');
    const best = input.orthologs.filter((o) => o.is_best_score === 1).slice(0, 15);
    out.push('| Species | Symbol | Methods |');
    out.push('|---|---|---|');
    for (const o of best) {
      out.push(
        `| ${fence(o.species)} | ${fence(o.ortholog_symbol)} | ${o.algorithms_match}/${o.out_of_algorithms} |`,
      );
    }
    out.push('');
  }

  if (input.go.length > 0) {
    out.push('## GO annotations');
    const grouped: Record<string, GoAnnotation[]> = { BP: [], MF: [], CC: [] };
    for (const a of input.go) {
      (grouped[a.namespace] ?? (grouped[a.namespace] = [])).push(a);
    }
    for (const ns of ['BP', 'MF', 'CC']) {
      const rows = grouped[ns] ?? [];
      if (rows.length === 0) continue;
      out.push(`### ${ns}`);
      for (const r of rows.slice(0, 30)) {
        out.push(`- \`${r.go_id}\` ${r.name} _(${r.evidence_code})_`);
      }
      out.push('');
    }
  }

  if (input.phenotypes.length > 0) {
    out.push('## Phenotypes');
    for (const p of input.phenotypes.slice(0, 30)) {
      out.push(
        `- \`${p.term_id}\` ${p.name} _(${p.n_alleles} allele${p.n_alleles === 1 ? '' : 's'})_`,
      );
    }
    out.push('');
  }

  if (input.anatomy.length > 0) {
    out.push('## Tissue expression');
    out.push(
      input.anatomy
        .slice(0, 30)
        .map((t) => t.name)
        .join(', '),
    );
    out.push('');
  }

  if (input.cengen.length > 0) {
    out.push('## CeNGEN neuronal expression');
    out.push('| Neuron type | TMM | Threshold passed |');
    out.push('|---|---:|---|');
    const TH = ['none', 'liberal', 'medium', 'conservative', 'stringent'];
    for (const r of input.cengen.slice(0, 30)) {
      out.push(
        `| ${r.neuron_type} | ${r.tmm !== null ? r.tmm.toFixed(1) : '–'} | ${TH[r.max_threshold ?? 0]} |`,
      );
    }
    out.push('');
  }

  if (input.cengenCoexpr.length > 0) {
    out.push('## Co-expressed in CeNGEN neurons');
    out.push('| Pearson | Gene | Description |');
    out.push('|---:|---|---|');
    for (const n of input.cengenCoexpr) {
      out.push(
        `| ${n.pearson.toFixed(3)} | ${fence(n.gene_name ?? n.wormbase_gene)} | ${fence(n.concise_description)} |`,
      );
    }
    out.push('');
  }

  if (input.neuronal.length > 0) {
    out.push('## Neuronal classification');
    out.push(input.neuronal.map((n) => `${n.category} (${n.supercategory})`).join(', '));
    out.push('');
  }

  out.push(citationFooter(v));
  return out.join('\n');
}

export interface GseaReportInput {
  kind: string;
  nGenes: number;
  params: { minSize: number; maxSize: number; nperm: number; multilevel: boolean };
  results: GseaResult[];
}

export async function buildGseaReport(input: GseaReportInput): Promise<string> {
  const v = await fetchVersion();
  const out: string[] = [];
  out.push(`# GSEA preranked — ${input.kind}`);
  out.push('');
  out.push(`**Input:** ${input.nGenes.toLocaleString()} ranked genes`);
  out.push(
    `**Params:** minSize=${input.params.minSize}, maxSize=${input.params.maxSize}, perms=${input.params.nperm}, multilevel=${input.params.multilevel}`,
  );
  out.push('');
  const sig = input.results.filter((r) => r.q <= 0.25);
  out.push(`## ${sig.length} significant terms (q ≤ 0.25)`);
  out.push('');
  out.push('| Term | Name | Size | NES | p | q |');
  out.push('|---|---|---:|---:|---:|---:|');
  for (const r of sig.slice(0, 100)) {
    out.push(
      `| \`${r.term_id}\` | ${fence(r.name)} | ${r.size} | ${r.nes.toFixed(2)} | ${r.p.toExponential(2)} | ${r.q.toExponential(2)} |`,
    );
  }
  out.push('');
  if (sig.length > 0) {
    out.push('## Leading edges');
    for (const r of sig.slice(0, 20)) {
      out.push(`### ${r.name} \`${r.term_id}\` (NES ${r.nes.toFixed(2)})`);
      out.push(r.leading_edge.join(', '));
      out.push('');
    }
  }
  out.push(citationFooter(v));
  return out.join('\n');
}

// BibTeX for all data sources, pinned to the exact build versions via version.json.
export async function buildCitationBibtex(): Promise<string> {
  const v = await fetchVersion();
  const src = (v?.sources ?? {}) as any;
  const wb = src.wormbase?.release ?? '?';
  const wbDate = src.wormbase?.date ?? '';
  const goDate = src.go?.date ?? '';
  const biogrid = src.biogrid?.version ?? '?';
  const expr = src.alliance_expression?.version ?? '?';
  const cengen = src.cengen?.release ?? '';
  const built = v?.built_at ?? new Date().toISOString();

  const entries: string[] = [];
  entries.push(`@misc{wormbase_${wb},
  title = {WormBase: a comprehensive resource for Caenorhabditis elegans biology},
  author = {{WormBase Consortium}},
  year = {${wbDate.slice(0, 4) || new Date().getFullYear()}},
  note = {Release ${wb}, accessed ${wbDate || built.slice(0, 10)}},
  url = {https://wormbase.org}
}`);
  entries.push(`@article{ashburner2000_go,
  title = {Gene Ontology: tool for the unification of biology},
  author = {Ashburner, M and Ball, C A and Blake, J A and Botstein, D and others},
  journal = {Nature Genetics},
  volume = {25},
  pages = {25-29},
  year = {2000},
  doi = {10.1038/75556},
  note = {Snapshot ${goDate || 'current'}}
}`);
  entries.push(`@article{stark2006_biogrid,
  title = {BioGRID: a general repository for interaction datasets},
  author = {Stark, Chris and Breitkreutz, Bobby-Joe and Reguly, Teresa and Boucher, Lorrie and Breitkreutz, Ashton and Tyers, Mike},
  journal = {Nucleic Acids Research},
  volume = {34},
  pages = {D535-D539},
  year = {2006},
  doi = {10.1093/nar/gkj109},
  note = {Version ${biogrid}}
}`);
  entries.push(`@article{alliance_2024,
  title = {Updates to the Alliance of Genome Resources central infrastructure},
  author = {{Alliance of Genome Resources Consortium}},
  journal = {GENETICS},
  year = {2024},
  doi = {10.1093/genetics/iyae049},
  note = {Expression data version ${expr}}
}`);
  if (cengen) {
    entries.push(`@article{barrett2022_cengen,
  title = {Integrating bulk and single cell RNA-seq refines transcriptomic profiles of individual C. elegans neurons},
  author = {Barrett, A and Taylor, S R and Hammarlund, M and others},
  journal = {eLife},
  year = {2022},
  note = {CeNGEN release ${cengen}; https://www.cengen.org}
}`);
  }
  entries.push(`@misc{wbrsht_${(v?.version ?? 'local').replace(/[^A-Za-z0-9]/g, '_')},
  title = {wormie.rs.ht: a local-first C. elegans gene explorer},
  author = {{wormie.rs.ht}},
  year = {${built.slice(0, 4)}},
  note = {Build ${v?.version ?? 'local'}, exported ${new Date().toISOString()}}
}`);
  return entries.join('\n\n') + '\n';
}

export function downloadBibtex(content: string, filename = `wb_rs_ht_citations.bib`) {
  const blob = new Blob([content], { type: 'application/x-bibtex' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}

export function downloadMarkdown(content: string, filename: string) {
  const blob = new Blob([content], { type: 'text/markdown' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}
